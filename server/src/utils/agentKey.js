'use strict';

const crypto = require('crypto');
const config = require('../config');

// =============================================================================
// Хэш ключа printer-agent — БЫСТРЫЙ (HMAC-SHA256), не bcrypt.
//
// bcrypt намеренно медленный — это правильно для ЧЕЛОВЕЧЕСКИХ паролей (низкая
// энтропия, нужно замедлить перебор). Ключ агента — это не пароль: 48 hex-
// символов из crypto.randomBytes(24), т.е. 192 бита случайной энтропии.
// Перебором такой ключ не подобрать НИКАКОЙ скоростью хэширования — медленный
// bcrypt тут не даёт защиты, а только сжигает CPU.
//
// А сжигает много: агент опрашивает сервер раз в 1.5 сек НА КАЖДЫЙ принтер, и
// раньше каждый такой опрос делал bcrypt.compare — при cost=10 это ~120 мс
// CPU-времени на один вызов (проверено бенчмарком). При 50 принтерах это уже
// больше 4 секунд CPU-работы в реальную секунду — то есть свыше 2 ядер VPS
// уходило бы ТОЛЬКО на проверку ключей агентов, раньше, чем на что-либо ещё.
// HMAC-SHA256 делает то же самое за ~0.006 мс — в 20 000 раз быстрее,
// печатных заданий это никак не касается, безопасность не страдает (энтропия
// ключа та же), а сервер выдерживает на порядки больше принтеров одновременно.
//
// Старые ключи, выпущенные ДО этого изменения, хранятся в agent_key_hash
// (bcrypt) — они продолжают работать через медленный путь в agentKeyAuth,
// пока их не перевыпустят; новые ключи сразу идут в agent_key_sha256.
// =============================================================================

function hashAgentKey(rawKey) {
  return crypto.createHmac('sha256', config.jwt.secret).update(rawKey).digest('hex');
}

function verifyAgentKey(rawKey, storedHex) {
  const computed = hashAgentKey(rawKey);
  const a = Buffer.from(computed, 'hex');
  const b = Buffer.from(String(storedHex || ''), 'hex');
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

module.exports = { hashAgentKey, verifyAgentKey };
