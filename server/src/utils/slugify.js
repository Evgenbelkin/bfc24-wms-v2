'use strict';

// =============================================================================
// Транслитерация + слаг из произвольного текста (название компании, принтера
// и т.п.) — используется там, где раньше от пользователя требовался отдельный
// "технический код", который он не понимал, зачем вводить (tenant_code при
// регистрации, printer_code при создании принтера). Теперь код подбирается
// сам, пользователь его вообще не видит.
// =============================================================================

const TRANSLIT_MAP = {
  а:'a',б:'b',в:'v',г:'g',д:'d',е:'e',ё:'e',ж:'zh',з:'z',и:'i',й:'y',к:'k',л:'l',м:'m',
  н:'n',о:'o',п:'p',р:'r',с:'s',т:'t',у:'u',ф:'f',х:'h',ц:'c',ч:'ch',ш:'sh',щ:'sch',
  ъ:'',ы:'y',ь:'',э:'e',ю:'yu',я:'ya',
};

function slugify(text, maxLen = 40) {
  let out = '';
  for (const ch of String(text || '').toLowerCase()) out += (TRANSLIT_MAP[ch] !== undefined ? TRANSLIT_MAP[ch] : ch);
  out = out.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').replace(/-{2,}/g, '-');
  return out.slice(0, maxLen) || 'x';
}

module.exports = { slugify };
