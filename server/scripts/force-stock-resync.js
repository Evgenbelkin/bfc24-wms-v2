'use strict';

require('dotenv').config();
const wbStockSync = require('../src/jobs/wbStockSync');

// =============================================================================
// Разовый форс-пересчёт и пуш остатков во WB по ВСЕМ тенантам/аккаунтам -
// вызывает ту же самую (уже проверенную, работающую раз в 8ч по расписанию)
// логику wbStockSync.runOnce(), просто вне расписания. Нужен один раз после
// возврата реактивного пуша по заказам (см. коммит "fix(wb): вернуть точечный
// реактивный пуш остатка по новым FBS-заказам", 29.08.2026) - чтобы сразу
// закрыть уже накопившиеся за время без реактивного пуша расхождения, а не
// ждать пока их закроет случайное событие (приёмка/инвентаризация) или
// ближайший плановый прогон.
//
// Безопасно гонять повторно - идемпотентно, просто пересчитывает текущее
// состояние (physical - open orders - reserve) и пушит.
//
// Запуск (из server/): node scripts/force-stock-resync.js
// =============================================================================

wbStockSync.runOnce()
  .then(() => {
    console.log('Готово: полный пересчёт и пуш остатков во WB по всем тенантам завершён.');
    process.exit(0);
  })
  .catch(e => {
    console.error('FATAL:', e);
    process.exit(1);
  });
