-- =============================================================================
-- BFC24 WMS v2 — Migration 011: Normalize location codes to uppercase
-- =============================================================================
-- Баг: ячейки создавались с кодом ровно в том регистре, как ввёл пользователь
-- (например "bufer", "test"), а сравнение при закрытии волны сборки и при
-- подтверждении упаковки делает .toUpperCase() перед сравнением ("BUFER").
-- Точное текстовое совпадение поэтому не находило реально существующую
-- ячейку — "Ячейка 'BUFER' не найдена на этом складе", хотя она есть.
--
-- Фикс на уровне приложения: createLocation теперь всегда сохраняет код
-- в верхнем регистре для новых ячеек. Эта миграция приводит к тому же виду
-- уже существующие ячейки, чтобы старые данные не ломались точно так же.
-- =============================================================================

BEGIN;

-- Пропускаем строку, если апперкейс-версия кода уже занята ДРУГОЙ ячейкой на
-- том же складе (иначе упёрлись бы в UNIQUE(tenant_id, warehouse_id, location_code)) —
-- такие редкие коллизии придётся развести вручную через экран "Места хранения".
UPDATE wms.locations l
SET location_code = UPPER(l.location_code), updated_at = NOW()
WHERE l.location_code <> UPPER(l.location_code)
  AND NOT EXISTS (
    SELECT 1 FROM wms.locations l2
    WHERE l2.tenant_id = l.tenant_id AND l2.warehouse_id = l.warehouse_id
      AND l2.location_code = UPPER(l.location_code) AND l2.id <> l.id
  );

COMMIT;
