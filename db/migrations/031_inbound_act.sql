-- =============================================================================
-- BFC24 WMS v2 — Migration 031: Акт приёмки товара на склад
-- =============================================================================
-- Формируется по заявке (wms.inbound_orders) кнопкой "Сформировать акт" после
-- начала приёмки. Печатается из браузера (без серверного PDF), но поля
-- сохраняются на заявке — чтобы акт можно было пересмотреть/перепечатать
-- позже без повторного ввода данных.
--
-- Юридические реквизиты сторон акта ("Заказчик" = клиент, "Исполнитель" =
-- сам тенант/ИП) сейчас нигде в системе не хранятся - добавляем их на
-- platform.tenants и wms.clients.
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- Реквизиты "Исполнителя" (сам тенант) — для самостоятельного заполнения
-- tenant_admin через новую страницу "Реквизиты компании"
-- ---------------------------------------------------------------------------
ALTER TABLE platform.tenants
  ADD COLUMN legal_name    TEXT,  -- полное юр. наименование ("ИП Иванов Иван Иванович")
  ADD COLUMN inn           TEXT,
  ADD COLUMN ogrnip        TEXT,
  ADD COLUMN legal_address TEXT;

-- ---------------------------------------------------------------------------
-- Реквизиты "Заказчика" (клиент фулфилмента)
-- ---------------------------------------------------------------------------
ALTER TABLE wms.clients
  ADD COLUMN legal_name    TEXT,
  ADD COLUMN inn           TEXT,
  ADD COLUMN legal_address TEXT;

-- ---------------------------------------------------------------------------
-- Поля акта приёмки на самой заявке
-- ---------------------------------------------------------------------------
ALTER TABLE wms.inbound_orders
  ADD COLUMN act_number         TEXT,           -- номер акта (по умолчанию = order_number)
  ADD COLUMN act_supplier       TEXT,           -- поставщик/отправитель груза
  ADD COLUMN act_boxes_count    INT,            -- кол-во грузовых мест (коробов)
  ADD COLUMN act_pallets_count  INT,            -- кол-во паллет
  ADD COLUMN act_weight_kg      NUMERIC(10,2),  -- вес груза
  ADD COLUMN act_carrier        TEXT,           -- перевозчик/транспортная компания
  ADD COLUMN act_source_doc     TEXT,           -- реквизиты товарной накладной/УПД
  ADD COLUMN act_packaging_ok   BOOLEAN,        -- TRUE = без замечаний, FALSE = с замечаниями
  ADD COLUMN act_remarks        TEXT,           -- текст замечаний к упаковке/товару
  ADD COLUMN act_client_signer  TEXT,           -- ФИО подписанта со стороны Заказчика ("Сдал")
  ADD COLUMN act_operator_signer TEXT,          -- ФИО подписанта со стороны Исполнителя ("Принял")
  ADD COLUMN act_city           TEXT,           -- город составления акта
  ADD COLUMN act_generated_at   TIMESTAMPTZ,    -- когда акт впервые сформирован
  ADD COLUMN act_generated_by   INT REFERENCES wms.users(id);

COMMIT;
