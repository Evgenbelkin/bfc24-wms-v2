-- =============================================================================
-- Контекст (обсуждено с пользователем): у существующего режима marking_mode=
-- 'scan' регистрация кода на приёмке ОБЯЗАТЕЛЬНА (см. shouldMarkAt в
-- marking.service.js - для 'scan' маркировка требуется на ОБОИХ этапах
-- всегда). Части клиентов это не подходит: код на товар клеится, но ФФ не
-- хочет/не может сканировать его на приёмке (например, приёмка идёт большими
-- партиями без поштучного контроля) - код должен сканироваться и
-- регистрироваться ВПЕРВЫЕ прямо на упаковке, одним действием, привязываться
-- к штрихкоду товара и уходить на выгрузку в Excel (обычно вместе с
-- settings.marking_wb_submit_disabled=true у клиента, см. миграцию 044 - но
-- это не обязательно, работает и с прямой отправкой в WB как у обычного
-- 'scan').
--
-- Намеренно НЕ переиспользуем существующий marking_trigger для этого - UI
-- всегда шлёт marking_trigger='packing' по умолчанию даже для marking_mode=
-- 'scan' (поле там просто скрыто и не участвует), так что почти у всех уже
-- существующих 'scan'-товаров в базе marking_trigger уже стоит 'packing' -
-- если бы новый сценарий определялся через trigger, ВСЕ существующие
-- двухшаговые scan-товары (приёмка+упаковка) внезапно превратились бы в
-- одношаговые. Поэтому - отдельное явное значение marking_mode, риска
-- случайно задеть существующие товары нет вообще (новые товары его получают
-- только явным выбором в форме).
-- =============================================================================

BEGIN;

DO $$
DECLARE
  con_name text;
BEGIN
  SELECT conname INTO con_name
  FROM pg_constraint
  WHERE conrelid = 'wms.items'::regclass
    AND contype = 'c'
    AND pg_get_constraintdef(oid) LIKE '%marking_mode%';
  IF con_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE wms.items DROP CONSTRAINT %I', con_name);
  END IF;
END $$;

ALTER TABLE wms.items
  ADD CONSTRAINT items_marking_mode_check
  CHECK (marking_mode IN ('print', 'scan', 'scan_packing'));

COMMIT;
