-- =============================================================================
-- BFC24 WMS v2 — Migration 061: Общий пул остатков между клиентами тенанта
-- =============================================================================
-- Задача (15.09.2026, клиент "ООО Эсэндди"): один и тот же физический товар
-- одного производства продаётся через НЕСКОЛЬКО разных клиентов тенанта
-- (разные ИП/ООО = разные WB-кабинеты одного и того же бренда/производителя).
-- Штрихкод у товара при этом буквально один и тот же. Сейчас wms.items
-- уникален по (tenant_id, client_id, barcode) — то есть один и тот же товар
-- заводится ОТДЕЛЬНОЙ строкой (и отдельным остатком/ячейкой) под каждого
-- клиента, хотя физически это один и тот же товар на одной полке.
--
-- Решение: НЕ трогаем существующую модель (клиент -> свой item -> свой
-- остаток, всё как раньше, по умолчанию выключено и ничего не ломает).
-- Добавляем опциональный слой поверх:
--   1. "Пул" — обычный wms.clients, просто с пометкой is_pool=true. Ничего
--      особенного в коде для него не нужно — приёмка на него работает как
--      на любого другого клиента "из коробки".
--   2. wms.item_pool_links — явная связка "этот item конкретного клиента ->
--      вот этот item пул-клиента". Только явная (админом), не автоматическая
--      по совпадению штрихкода — совпадение может быть случайным у разных
--      клиентов, а цена ошибки высокая (физически смешаем чужой товар).
--   3. Флаг на тенанте — включает саму фичу (резолв через пул) целиком.
--      Без него весь новый код проходит "насквозь" и ведёт себя как раньше.
--
-- Сам резолвер (item/client -> пуловый item/client для чтения/записи
-- остатка) и его подключение в размещение/сборку/проверку остатка при
-- формировании волны — отдельные шаги (см. таск-трекер, задачи #113-122).
-- =============================================================================

BEGIN;

-- Пул — обычный клиент с пометкой. Не показывать в списках "реальных"
-- клиентов (биллинг, личный кабинет и т.п.) - фильтровать по is_pool=false
-- в соответствующих местах UI/API по мере необходимости; в приёмке, наоборот,
-- должен быть виден и выбираем как обычный клиент.
ALTER TABLE wms.clients ADD COLUMN IF NOT EXISTS is_pool BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX IF NOT EXISTS idx_clients_is_pool ON wms.clients(tenant_id, is_pool) WHERE is_pool = TRUE;

-- Включение фичи на уровне тенанта — по умолчанию выключено везде.
ALTER TABLE platform.tenants ADD COLUMN IF NOT EXISTS item_pooling_enabled BOOLEAN NOT NULL DEFAULT FALSE;

-- Связка "item конкретного клиента" -> "item пул-клиента". Один item
-- реального клиента может быть связан максимум с одним пулом (UNIQUE на
-- item_id) — если понадобится другая топология, это будет отдельное
-- обсуждение, сейчас это не нужно и только упрощает резолвер.
CREATE TABLE wms.item_pool_links (
  id            BIGSERIAL   PRIMARY KEY,
  tenant_id     INT         NOT NULL REFERENCES platform.tenants(id) ON DELETE CASCADE,
  item_id       INT         NOT NULL UNIQUE REFERENCES wms.items(id) ON DELETE CASCADE,
  pool_item_id  INT         NOT NULL REFERENCES wms.items(id) ON DELETE CASCADE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by    INT         REFERENCES wms.users(id),
  CHECK (item_id <> pool_item_id)
);

CREATE INDEX idx_item_pool_links_pool_item ON wms.item_pool_links(pool_item_id);
CREATE INDEX idx_item_pool_links_tenant    ON wms.item_pool_links(tenant_id);

-- Отдельный тип движения для разового переноса УЖЕ существующего остатка
-- клиента в пул при первой настройке связки (см. scripts/item-pool-admin.js
-- transfer) - чтобы в истории/отчётах это было явно отличимо от обычного
-- перемещения ('move') или ручной корректировки ('adjust').
ALTER TYPE wms.movement_type ADD VALUE IF NOT EXISTS 'pool_merge';

COMMIT;
