-- Контекст (владелец, 20.09.2026: "в 'ждут выгрузки' почему то одинаковое
-- время у кизов, разве так должно быть? просто проданы они в разное время а
-- не в одно"). Дедлайн "вывод из оборота" (marking.service.js::getPendingWithdrawal)
-- считался от wms.wb_order_status_events.observed_at — момента, когда НАШ
-- job увидел статус 'sold' при опросе (раз в ~30 минут), а не от реального
-- времени продажи, которого WB в статусном опросе вообще не отдаёт. Заказы,
-- перешедшие в 'sold' в одном и том же опросе, получали почти одинаковый
-- дедлайн — отсюда и симптом.
--
-- Реальное время продажи есть в Statistics API /api/v1/supplier/sales (поле
-- date), матчится по тому же ключу srid=rid, что уже подтверждён и
-- используется в миграции 053 (регион/округ покупателя). Отдельная таблица
-- не нужна — это тоже 1:1 к заказу, как и поля из 053.
-- =============================================================================

BEGIN;

ALTER TABLE wms.wb_orders
  ADD COLUMN IF NOT EXISTS actual_sale_at   TIMESTAMPTZ, -- date из /api/v1/supplier/sales (реальное время продажи, не создания заказа)
  ADD COLUMN IF NOT EXISTS sales_synced_at  TIMESTAMPTZ; -- когда в последний раз обновили actual_sale_at из Statistics API

COMMIT;
