-- =============================================================================
-- BFC24 WMS v2 — Migration 039: Отмена зависшей отгрузки
-- =============================================================================
-- Проблема: если упаковка блокируется (например, код "Честный знак" не
-- найден в пуле) и продавец в итоге отгружает заказ прямо в кабинете WB в
-- обход ВМС, отгрузка (wms.shipments) остаётся в незавершённом статусе
-- НАВСЕГДА — реконсиляция wb_orders её не видит (см. комментарий в
-- wb.service.js: реконсиляция работает только для заказов БЕЗ wb_supply_id,
-- а у отгрузки он уже есть). Раньше снять такую отгрузку с учёта было
-- нечем — статус 'cancelled' в wms.shipment_status существовал с самого
-- начала (миграция 006), но ни один код его никогда не проставлял.
--
-- Добавляем только аудит отмены (кто/когда/почему) — сам статус 'cancelled'
-- уже есть в enum, менять его не нужно.
-- =============================================================================
BEGIN;

ALTER TABLE wms.shipments
  ADD COLUMN cancelled_at    TIMESTAMPTZ,
  ADD COLUMN cancelled_by    INT REFERENCES wms.users(id),
  ADD COLUMN cancel_reason   TEXT;

COMMENT ON COLUMN wms.shipments.cancel_reason IS
  'Причина отмены отгрузки администратором/супервайзером (например: "отгружено напрямую через кабинет WB в обход ВМС, упаковка была заблокирована")';

COMMIT;
