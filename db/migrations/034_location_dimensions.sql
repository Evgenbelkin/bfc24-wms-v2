-- =============================================================================
-- BFC24 WMS v2 — Migration 034: физические размеры ячейки
-- =============================================================================
-- Для визуализации заполняемости ячеек (сколько литров товара сейчас лежит
-- относительно вместимости) нужны физические габариты ячейки, а не только
-- предельный литраж max_volume_l (который раньше нигде не заполнялся). По
-- аналогии с wms.items (length_cm/width_cm/height_cm) — length_cm/width_cm/
-- height_cm задаются в сантиметрах; max_volume_l (уже существующее поле)
-- становится источником истины для вместимости в литрах и авторассчитывается
-- в locations.service.js из размеров при их указании (L*W*H/1000), либо может
-- быть задан напрямую, если размеры неизвестны/нерелевантны.
-- =============================================================================

BEGIN;

ALTER TABLE wms.locations
  ADD COLUMN length_cm NUMERIC(8,2),
  ADD COLUMN width_cm  NUMERIC(8,2),
  ADD COLUMN height_cm NUMERIC(8,2);

COMMIT;
