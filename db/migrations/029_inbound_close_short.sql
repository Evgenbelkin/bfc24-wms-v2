-- =============================================================================
-- BFC24 WMS v2 — Migration 029: ручное закрытие короткой поставки
-- =============================================================================
-- Раньше заявка на поставку могла стать 'completed' только когда ВСЕ строки
-- набрали ровно ожидаемое количество - если поставщик привёз меньше (обычная
-- ситуация), заявка навсегда зависала в 'in_progress'. Закрыть её принудительно
-- было нечем, кроме 'cancel', который по смыслу не то же самое (звучит как
-- "всё аннулировано", хотя фактически принятый товар остаётся на складе).
--
-- Статус 'partial' в wms.inbound_order_status уже существовал с самого начала
-- (миграция 005), но никогда не проставлялся кодом - используем его для этого
-- закрытия, плюс добавляем поля "когда/почему/кем закрыли".
-- =============================================================================

BEGIN;

ALTER TABLE wms.inbound_orders
  ADD COLUMN closed_at     TIMESTAMPTZ,
  ADD COLUMN closed_reason TEXT,
  ADD COLUMN closed_by     INT REFERENCES wms.users(id);

COMMIT;
