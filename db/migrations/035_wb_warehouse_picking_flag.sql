-- =============================================================================
-- BFC24 WMS v2 — Migration 035: флаг «обрабатывать этот склад WB в волнах»
-- =============================================================================
-- Проблема: если у клиента в одном WB-кабинете (mp_account) зарегистрировано
-- несколько собственных складов (например, в разных городах — Москва, Казань,
-- Екатеринбург — каждый обслуживается своим фулфилментом), то
-- /wb/generate-wave сейчас берёт заказы по ВСЕМ складам этого аккаунта и
-- сваливает их в одну волну сборки текущего тенанта. Нужно, чтобы конкретный
-- тенант (ФФ) явно указывал, какие склады WB он физически обслуживает.
--
-- is_enabled_for_picking — отдельный флаг от уже существующего
-- is_enabled_for_dist (тот — клиентский, для автораспределения остатков,
-- задаётся продавцом в его кабинете). Этот — админский, задаётся тенантом.
-- DEFAULT TRUE — обратная совместимость: пока админ явно не выключит склад,
-- поведение не меняется (как и раньше, забираются заказы со всех складов).
-- =============================================================================

BEGIN;

ALTER TABLE wms.wb_seller_warehouses
  ADD COLUMN is_enabled_for_picking BOOLEAN NOT NULL DEFAULT TRUE;

COMMIT;
