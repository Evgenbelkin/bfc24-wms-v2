-- =============================================================================
-- BFC24 WMS v2 — Migration 018: индекс под сортировку списка заказов WB
-- =============================================================================
-- GET /wb/orders фильтрует по tenant_id (+ опционально account_id/status/дата)
-- и всегда сортирует по created_at DESC с LIMIT. До этой миграции у
-- wms.wb_orders был индекс только на (tenant_id) без created_at — Postgres
-- находил все строки тенанта по индексу, но затем сортировал их ВСЕ по
-- created_at в памяти/на диске перед тем как отрезать LIMIT. По мере роста
-- таблицы (заказы копятся годами) это всё медленнее — сортировка растёт
-- вместе с историей, а не с размером страницы. Добавляем композитный
-- индекс (tenant_id, created_at DESC), который отдаёт уже отсортированные
-- строки напрямую, без отдельного шага сортировки.
-- =============================================================================
BEGIN;

CREATE INDEX idx_wb_orders_tenant_created ON wms.wb_orders(tenant_id, created_at DESC);

COMMIT;
