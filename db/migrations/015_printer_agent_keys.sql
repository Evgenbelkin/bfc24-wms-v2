-- =============================================================================
-- BFC24 WMS v2 — Migration 015: постоянный ключ доступа для агента печати
-- =============================================================================
-- Раньше printer-agent авторизовался обычным токеном входа сотрудника — тот
-- живёт ограниченное время (по умолчанию несколько часов), и когда истекал,
-- агент тихо переставал забирать задания: печать останавливалась без явной
-- ошибки на складе, задания просто копились в очереди со статусом 'new'.
--
-- Теперь у каждого принтера с подключением "через агент" может быть отдельный
-- постоянный ключ доступа (не привязан к учётке сотрудника, не истекает по
-- времени, отзывается/перевыпускается вручную из панели принтеров). Хранится
-- только bcrypt-хэш — сам ключ показывается администратору один раз, в момент
-- выпуска.
--
-- agent_last_seen_at обновляется при каждом успешном обращении агента —
-- панель принтеров показывает по нему "на связи" / "не выходил на связь Xч",
-- чтобы падение агента было видно сразу, а не тихо копилось в очереди.
-- =============================================================================
BEGIN;

ALTER TABLE wms.printers
  ADD COLUMN agent_key_hash     TEXT,
  ADD COLUMN agent_last_seen_at TIMESTAMPTZ;

COMMIT;
