-- =============================================================================
-- Инцидент 15-16.09.2026 (поставка WB-GI-278465437, клиент "ИП Макарова С.И."):
-- /generate-wave создаёт поставку на стороне WB (wbClient.createSupply), а
-- затем пытается добавить в неё заказы (addOrdersToSupply). Если WB отклоняет
-- конкретный заказ по причине, отличной от "успел пропасть из списка новых"
-- (тот единственный случай, который раньше умел обрабатывать retry), вторая
-- попытка падает с той же ошибкой, и это исключение раньше пробрасывалось
-- необработанным — локальная транзакция (создание wms.shipments/picking_tasks)
-- так и не выполнялась. В итоге поставка реально существует в кабинете WB
-- (пустая или частично заполненная), но полностью невидима в ВМС — узнать о
-- ней можно только постфактум, когда она "зависает на сборке" и продавцу
-- приходится отгружать её вручную мимо ВМС (что и произошло).
--
-- Правка в wb.router.js (generate-wave) теперь в таком тупиковом случае не
-- пробрасывает исключение молча, а создаёт shipment с этим новым статусом —
-- чтобы поставка была видна в ВМС (диспетчерская/финансы) сразу, а не
-- терялась. Новое значение enum добавляется отдельной транзакцией миграции
-- (ADD VALUE не может использоваться в той же транзакции, где добавлен) —
-- ничего не ломает, старый код, не знающий про 'error', просто никогда его
-- не производит и не обязан его явно обрабатывать.
-- =============================================================================

BEGIN;

ALTER TYPE wms.shipment_status ADD VALUE IF NOT EXISTS 'error';

COMMIT;
