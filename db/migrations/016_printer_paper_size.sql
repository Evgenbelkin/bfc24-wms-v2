-- =============================================================================
-- BFC24 WMS v2 — Migration 016: имя формата бумаги (Stock) для агента печати
-- =============================================================================
-- Разные модели/экземпляры термопринтеров могут иметь СВОИ именованные
-- варианты формата бумаги в настройках драйвера Windows (например, у
-- Xprinter это диалог Page Setup -> Stock, где помимо стандартных размеров
-- бывает кастомный именованный Stock вроде "58x40"). Печать через агента
-- (SumatraPDF, командная строка) должна ссылаться на этот формат ПО ИМЕНИ,
-- а не заново создавать generic custom-size с теми же числами — именованный
-- Stock в драйвере может нести свою калибровку (например, датчика зазора
-- между этикетками), которой нет у generic custom size с той же шириной и
-- высотой. Раньше это имя было зашито в код агента константой ("58x40") -
-- работало только для одного конкретного принтера/драйвера и не
-- масштабировалось на другие модели/принтеры.
--
-- paper_size_name — необязательное поле, настраивается вручную в панели
-- принтеров при заведении/редактировании принтера (нужно посмотреть точное
-- имя в диалоге настроек драйвера на складском ПК). Если не заполнено -
-- агент печатает как раньше, генерируя размер бумаги из фактических мм
-- (widthMm x heightMm), без привязки к конкретному именованному Stock.
-- =============================================================================
BEGIN;

ALTER TABLE wms.printers
  ADD COLUMN paper_size_name TEXT;

COMMIT;
