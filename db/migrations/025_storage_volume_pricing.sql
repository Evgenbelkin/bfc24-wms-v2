-- =============================================================================
-- BFC24 WMS v2 — Migration 025: Тарификация хранения по литражу
-- =============================================================================
-- До этой миграции billing.chargeStorageForClientToday() считал хранение
-- только одним способом: количество занятых ячеек (грузомест) × unit_price.
-- Для одежды (много размеров одной модели, у каждого свой объём) это грубо —
-- нужно тарифицировать по фактическому литражу товара, как это делает сам
-- Wildberries: N₽ за первый литр + M₽ за каждый следующий (округление литража
-- вверх). Ставки — per-client (как и весь остальной прайс-лист), поэтому
-- storage_mode/extra_unit_price добавлены прямо в billing.client_price_list,
-- а не как отдельная таблица.
--
-- storage_mode='slots'  (по умолчанию, прежнее поведение) — unit_price × кол-во
--   занятых ячеек с положительным остатком.
-- storage_mode='volume' — unit_price трактуется как цена за ПЕРВЫЙ литр,
--   extra_unit_price — цена за каждый последующий литр (объём товара берётся
--   из wms.items.volume_liters, округляется вверх после вычитания первого литра).
--   Для service_type, отличных от 'storage', оба новых поля игнорируются.
-- =============================================================================

BEGIN;

CREATE TYPE billing.storage_mode AS ENUM ('slots', 'volume');

ALTER TABLE billing.client_price_list
  ADD COLUMN storage_mode billing.storage_mode NOT NULL DEFAULT 'slots',
  ADD COLUMN extra_unit_price NUMERIC(14,4);

COMMIT;
