-- =============================================================================
-- BFC24 WMS v2 — Migration 020: ручное подтверждение доставки отгрузки
-- =============================================================================
-- Отгрузки, созданные НЕ через Wildberries (marketplace='manual', "Ручной
-- заказ") не имеют wb_orders/wb_supply_id — фоновая проверка через WB API
-- (syncDeliveryStatusForTenant, см. wb.service.js) их просто не видит и
-- никогда не переведёт в status='done' сама: спросить не у кого, у такой
-- отгрузки нет маркетплейса, который мог бы подтвердить приёмку. Реальный
-- кейс: MANUAL-заказ навсегда завис в 'in_transit'.
--
-- Добавляем ручное подтверждение — кнопка на карточке отгрузки, доступная
-- супервайзеру/админу, которая переводит отгрузку в 'done' вручную (человек
-- сам знает, что груз доставлен — например по подтверждению от курьера/ТК).
-- delivered_at/delivered_by — кто и когда это подтвердил, отдельно от
-- wb_accepted_at (это конкретно про подтверждение WB API) и wb_delivered_at
-- (когда МЫ сообщили WB об отгрузке) — три разных события.
-- =============================================================================
BEGIN;

ALTER TABLE wms.shipments ADD COLUMN IF NOT EXISTS delivered_at TIMESTAMPTZ;
ALTER TABLE wms.shipments ADD COLUMN IF NOT EXISTS delivered_by INT REFERENCES wms.users(id);

COMMIT;
