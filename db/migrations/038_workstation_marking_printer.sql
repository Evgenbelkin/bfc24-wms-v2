-- =============================================================================
-- BFC24 WMS v2 — Migration 038: Отдельный принтер под "Честный знак" на
-- рабочем месте
-- =============================================================================
-- Проблема: у рабочего места (wms.workstations) было только одно поле
-- default_printer_id, а resolvePrinter() отдавало его вообще без оглядки на
-- doc_type. При масштабе с раздельными принтерами на столе (стикер ВБ на
-- одном, коды "Честный знак" на другом) это не работало — оба документа
-- уезжали на один и тот же принтер.
--
-- Решение: второе, необязательное поле marking_printer_id. Если задано —
-- doc_type='marking_code' идёт туда, всё остальное (wb_sticker,
-- pick_list_label, shipping_qr и т.п.) — как раньше, на default_printer_id.
-- Если не задано (обычный случай, один принтер на стол) — ничего не меняется,
-- полностью обратная совместимость.
-- =============================================================================
BEGIN;

ALTER TABLE wms.workstations
  ADD COLUMN marking_printer_id INT REFERENCES wms.printers(id);

COMMENT ON COLUMN wms.workstations.marking_printer_id IS
  'Отдельный принтер под коды "Честный знак" (doc_type=marking_code). NULL - печатать туда же, куда и остальное (default_printer_id).';

COMMIT;
