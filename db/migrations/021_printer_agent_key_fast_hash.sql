-- =============================================================================
-- BFC24 WMS v2 — Migration 021: быстрый хэш ключа агента (вместо bcrypt)
-- =============================================================================
-- См. server/src/utils/agentKey.js — bcrypt.compare() на КАЖДЫЙ опрос агента
-- (раз в 1.5 сек на принтер) обходился ~120мс CPU (замер бенчмарком), что при
-- нескольких десятках принтеров само по себе съедало больше CPU, чем весь
-- остальной сервер. Ключ агента — не пароль (192 бита случайной энтропии из
-- crypto.randomBytes(24)), медленный bcrypt тут не даёт защиты, только жжёт CPU.
--
-- Новая колонка agent_key_sha256 — HMAC-SHA256 (~0.006мс). Старая agent_key_hash
-- (bcrypt) остаётся для уже выпущенных ключей, которые ещё не перевыпустили —
-- обратная совместимость, ничего не ломаем разом.
-- =============================================================================
BEGIN;

ALTER TABLE wms.printers ADD COLUMN IF NOT EXISTS agent_key_sha256 TEXT;

COMMIT;
