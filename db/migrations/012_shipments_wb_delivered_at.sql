-- =============================================================================
-- BFC24 WMS v2 — Migration 012: shipments.wb_delivered_at
-- =============================================================================
-- Баг: confirmShipment() у нас подтверждал отгрузку локально (status='in_transit'),
-- но НИКОГДА не сообщал об этом в саму Wildberries (метод "Подтвердить поставку
-- к отгрузке" — PATCH /api/v3/supplies/{id}/deliver — был написан в wb.client.js,
-- но нигде не вызывался). Поэтому в кабинете ВБ поставка так и оставалась
-- "На сборке", хотя у нас уже "Отгружена".
--
-- Добавляем метку времени, когда мы реально успешно сообщили ВБ о отгрузке —
-- нужна, чтобы: (1) не дёргать WB API повторно при каждом повторном скане уже
-- отгруженной поставки, и (2) дать возможность ПОВТОРИТЬ попытку для уже
-- отгруженных ранее (до этого фикса) поставок, у которых wb_delivered_at ещё
-- NULL — просто повторно отсканировав код поставки на экране отгрузки.
-- =============================================================================

BEGIN;

ALTER TABLE wms.shipments ADD COLUMN IF NOT EXISTS wb_delivered_at TIMESTAMPTZ;

COMMIT;
