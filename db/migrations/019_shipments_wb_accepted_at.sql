-- До этой миграции отгрузка переходила в status='in_transit' (скан QR поставки
-- упаковщиком/отгрузчиком) и на этом всё — ничего в системе не проверяло,
-- забрал ли WB поставку физически на своём складе. Счётчик "в пути" на табло
-- копился бесконечно, отгрузки годами оставались в in_transit.
--
-- wb_accepted_at — когда мы ПОСЛЕДНИЙ РАЗ через WB API (POST /api/v3/orders/status)
-- подтвердили, что WB реально принял заказы поставки (wbStatus вышел из
-- 'waiting') — в этот момент shipment переводится в status='done' фоновым
-- джобом (см. wb.service.js:syncDeliveryStatusForTenant). Отдельно от уже
-- существующего wb_delivered_at — тот фиксирует момент, когда МЫ сообщили
-- WB об отгрузке (исходящее действие), а wb_accepted_at — когда WB
-- подтвердил приёмку (входящее подтверждение), это разные события.
-- =============================================================================
BEGIN;

ALTER TABLE wms.shipments ADD COLUMN IF NOT EXISTS wb_accepted_at TIMESTAMPTZ;

COMMIT;
