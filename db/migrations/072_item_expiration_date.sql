-- =============================================================================
-- BFC24 WMS v2 — Migration 072: срок годности товара (для WB meta/expiration)
-- =============================================================================
-- Клиент СНД (косметика, несколько ИП-магазинов на WB): ВСЕ возвраты уходят
-- обратно продавцу вместо повторной продажи. Причина №2 (причина №1 — киз
-- ошибочно выводился из оборота после отгрузки, чинится отдельно передачей
-- киза сразу в упаковке) — WB требует срок годности товара на сборочном
-- задании (PUT /api/v3/orders/{orderId}/meta/expiration), без него возвращает
-- товар продавцу при возврате, а не пускает на повторную продажу.
--
-- Решение (обсуждение 21.09.2026, задача #59) — простой вариант "1" без
-- партионного/лот-учёта: срок годности хранится НА ТОВАРЕ (не на партии/
-- ячейке), задаётся массово сотрудниками/админом в справочнике товаров
-- (app/items.html), при скане киза на упаковке автоматически подтягивается
-- и уходит в WB тем же вызовом, что и код маркировки (см.
-- marking.service.js::consumeScannedCodeAtPacking, wb.client.js::setOrderExpiration).
--
-- Осознанный компромисс в точности (обсуждали с клиентом): если на складе
-- одновременно лежит старая и новая партия одного товара, в WB уйдёт то
-- значение, что стоит в карточке товара на момент скана, без разбора по
-- конкретной физической партии. Более точный вариант (привязка к ячейке
-- размещения/партии) обсуждался, но отложен как более затратный - могут
-- вернуться к нему позже, если точности этого варианта не хватит.
-- =============================================================================

BEGIN;

ALTER TABLE wms.items
  ADD COLUMN expiration_date DATE;

COMMENT ON COLUMN wms.items.expiration_date IS
  'Срок годности товара ("годен до"), задаётся вручную/массово в справочнике товаров. '
  'Источник значения для WB PUT /api/v3/orders/{orderId}/meta/expiration при скане киза на упаковке. '
  'WB требует минимум 30 дней от текущей даты на момент отправки - см. marking.service.js.';

COMMIT;
