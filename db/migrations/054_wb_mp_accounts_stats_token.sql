-- =============================================================================
-- BFC24 WMS v2 — Migration 054: отдельный read-only токен для Statistics API
-- =============================================================================
-- WB не позволяет комбинировать в одном токене разный уровень доступа по
-- категориям (весь токен целиком либо "Чтение и запись", либо "Только
-- чтение" - см. dev.wildberries.ru/openapi/api-information, раздел "Как
-- создать токен"). Наши клиенты дают токен с правами на запись для
-- Контент+Маркетплейс (нужно для карточек товаров и заказов) - такой токен
-- физически не может дополнительно нести read-only категорию "Статистика"
-- без того, чтобы вся "Статистика" тоже стала read-write, а на это клиенты
-- разумно не соглашаются.
--
-- Поэтому для функций, которым нужна только категория "Статистика" (сейчас -
-- регион/округ/СЦ покупателя на заказе, см. wb.service.js::
-- syncStatsRegionForAccount и fbsAnalytics.service.js::getRegionDeliveryTime),
-- заводим ОТДЕЛЬНОЕ необязательное поле под второй, read-only токен. Если оно
-- не заполнено - используем основной api_token как раньше (для аккаунтов,
-- где один токен уже покрывает всё, менять ничего не нужно).
-- =============================================================================

BEGIN;

ALTER TABLE wms.mp_accounts
  ADD COLUMN IF NOT EXISTS api_token_stats TEXT;

COMMENT ON COLUMN wms.mp_accounts.api_token_stats IS
  'Опциональный отдельный read-only токен WB (категория "Статистика") - используется вместо api_token только для вызовов Statistics API, когда основной токен не покрывает эту категорию (см. 054_wb_mp_accounts_stats_token.sql)';

COMMIT;
