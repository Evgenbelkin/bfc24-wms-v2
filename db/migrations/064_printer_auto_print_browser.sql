-- =============================================================================
-- BFC24 WMS v2 — Migration 064: явный переключатель "тихой" автопечати в
-- браузере (без агента печати) для принтеров connection_type='usb'
-- =============================================================================
-- Контекст (17.09.2026, слабый интернет у ЭсЭнДи): для connection_type='usb'
-- сделали автопечать стикера ВБ прямо в браузере сразу после скана, минуя
-- агента (см. packing.service.js::scanItem, printerResolver.js). НО
-- connection_type='usb' уже существовал раньше как отдельный, самостоятельный
-- вариант ("печать через обычное диалоговое окно браузера" — кнопка "Печать
-- ещё раз" в packing.html) — если завязать автопечать НАПРЯМУЮ на
-- connection_type='usb', у любого уже существующего такого принтера скан
-- внезапно начал бы сам печатать без предупреждения. Нужен отдельный явный
-- флаг, включаемый осознанно за конкретный принтер, а не выводимый неявно из
-- способа подключения.
BEGIN;

ALTER TABLE wms.printers
  ADD COLUMN IF NOT EXISTS auto_print_browser BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN wms.printers.auto_print_browser IS
  'Автопечать в браузере сразу после скана (без агента, без print_jobs) — действует ТОЛЬКО вместе с connection_type=''usb''. По умолчанию выключено, включается явно за конкретный принтер.';

COMMIT;
